SCENARIOS = {f.__name__: f for f in (
    heure, meteo, culture, calcul, histoire_suite, correction_anglais, ajout_apres,
    nouvelle_demande, cloture, autre_personne, inachevee, accueil, recherche_web, memoire,
    remerciement)}  # fmt: skip


async def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--tag", default="run")
    parser.add_argument("--only", default="", help="comma-separated scenario names")
    parser.add_argument("--repeat", type=int, default=1)
    parser.add_argument("--brain", default="", help="delegation model (qwen, qwen3.5, gemma)")
    args = parser.parse_args()
    config = load_config()
    names = [n for n in args.only.split(",") if n] or list(SCENARIOS)

    async def fake_searxng(_http, _config, query):
        return WEB

    search.searxng = fake_searxng
    report = {"date": datetime.now().isoformat(timespec="seconds"), "tag": args.tag,
              "brain": args.brain or config.llm.model, "runs": []}  # fmt: skip
    async with aiohttp.ClientSession(connector=aiohttp.TCPConnector(force_close=True)) as http:
        harness = Harness(http, config, args.brain or None)
        for repeat in range(args.repeat):
            for name in names:
                run = Run(name)
                started = time.perf_counter()
                try:
                    await asyncio.wait_for(SCENARIOS[name](harness, run), 180)
                except Exception as exc:  # noqa: BLE001
                    run.checks["sans erreur"] = False
                    run.warnings.append(f"{type(exc).__name__}: {exc}")
                if "sans erreur" not in run.checks:
                    run.checks["oral propre"] = clean_speech(run)
                ok = sum(run.checks.values())
                print(f"{name:20s} {ok}/{len(run.checks)} {time.perf_counter() - started:5.1f} s"
                      f"  {' '.join(k for k, v in run.checks.items() if not v)}", flush=True)
                report["runs"].append({**run.__dict__, "repeat": repeat})
    total = sum(len(r["checks"]) for r in report["runs"])
    passed = sum(sum(r["checks"].values()) for r in report["runs"])
    audio = [ms for r in report["runs"] for ms in r["first_audio_ms"]]
    report["score"] = f"{passed}/{total}"
    report["first_audio_median_ms"] = round(statistics.median(audio)) if audio else None
    print(f"Score {passed}/{total}  premier son médian {report['first_audio_median_ms']} ms")
    out = ROOT / ".runtime" / "bench" / f"prompts-{args.tag}.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, ensure_ascii=False, indent=1), "utf-8")
    print(f"Détails : {out}")


if __name__ == "__main__":
    asyncio.run(main())

async def inachevee(h, run):
    s = await h.session(run)
    await s.on_user_text("Mets un minuteur de", unfinished=True)
    await h.idle(s)
    text = spoken(run)
    run.checks["aucun outil"] = not run.tools
    run.checks["invite à continuer"] = len(text) < 80 and "?" in text or "écoute" in text.lower()
    await s.close("bench")


async def accueil(h, run):
    s = await h.session(run)
    await s.handle({"type": "session.commentary.append", "content": "Démarre en saluant.",
                    "delegation_id": None})  # fmt: skip
    await h.idle(s)
    text = spoken(run).lower()
    run.checks["salue"] = bool(re.search(r"bonjour|salut|coucou|bonsoir|hello", text))
    run.checks["ne lit pas la consigne"] = "démarre" not in text and "saluant" not in text
    run.checks["court"] = len(run.said) <= 2
    await s.close("bench")



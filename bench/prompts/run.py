r"""Prompt bench: Cornelius' real session through Localive's real reply and decision chain.

The session configuration is generated by Cornelius' own code (``cornelius_session.json``:
Live instructions, Responses delegation, card and module tools). Replies come from the
running brain, decisions and plans from the running arbiter. Only the voice (a fake TTS that
takes about as long as speech, sped up) and the tool results (fixtures) are simulated.

    .venv\Scripts\python.exe bench\prompts\run.py --tag before
    .venv\Scripts\python.exe bench\prompts\run.py --tag after --only correction_anglais

Needs Localive (or its llama-servers) running: brain on llm.url, arbiter on decision.port.
Checks are automatic and deliberately simple; read the saved transcripts too.
"""


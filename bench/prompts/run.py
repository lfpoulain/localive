WEB = [search.Result("Grand Prix du Brésil 2026 : victoire de Lando Norris",
                     "https://www.example.org/f1/bresil-2026",
                     "Lando Norris a remporté le Grand Prix du Brésil le 8 novembre 2026.")]


class FakeTts:
    def __init__(self) -> None:
        self.texts: list[str] = []

    async def stream(self, text: str, voice: str):
        self.texts.append(text)
        seconds = max(0.4, len(text) / CHARS_PER_S) / SPEED
        for _ in range(4):
            await asyncio.sleep(seconds / 4)
            yield np.full(int(24000 * seconds / 4), 0.2, dtype=np.float32)


class NoTranscriber:
    label = "text"


@dataclass
class Run:
    name: str
    said: list[str] = field(default_factory=list)  # sentences actually played
    tools: list[tuple[str, dict]] = field(default_factory=list)
    decisions: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    interrupted: int = 0
    first_audio_ms: list[float] = field(default_factory=list)
    checks: dict[str, bool] = field(default_factory=dict)


class Harness:
    def __init__(self, http: aiohttp.ClientSession, config, brain: str | None) -> None:
        self.http, self.config, self.brain = http, config, brain

    async def session(self, run: Run) -> LiveSession:
        services = Services(
            config=self.config, http=self.http, transcriber=NoTranscriber(),
            chat=ChatClient(self.http, self.config.llm), tts=FakeTts(),
            make_segmenter=Segmenter, arbiter=Arbiter(self.http, self.config),
        )  # fmt: skip
        holder: dict[str, LiveSession] = {}

        async def receive(event: dict) -> None:
            kind = event["type"]
            if kind == "session.output_transcript.delta":
                run.said.append(event["delta"].strip())
            elif kind == "voice.interrupted":
                run.interrupted += 1
            elif kind == "voice.provider_warning":
                run.warnings.append(event["error"].get("message", event["error"]["code"]))
            elif kind == "localive.decision":
                run.decisions.append(f"{event['decision']}/{event['label']}")
            elif kind == "response.event":
                inner = event["event"]
                item = inner.get("item") or {}
                if inner["type"] == "response.output_item.done" and \
                        item.get("type") == "function_call":
                    args = json.loads(item["arguments"] or "{}")
                    run.tools.append((item["name"], args))
                    reply = {"type": "function_call_output", "call_id": item["call_id"],
                             "output": json.dumps(RESULTS.get(item["name"], {"status": "failed"}),
                                                  ensure_ascii=False)}  # fmt: skip
                    asyncio.get_running_loop().call_later(0.15, lambda: asyncio.ensure_future(
                        holder["s"].handle({"type": "response.item.create", "item": reply})))
                elif item.get("type") == "web_search_call" and inner["type"].endswith("added"):
                    run.tools.append(("web_search", item.get("action", {})))
            elif kind == "localive.turn" and event.get("first_audio_ms") is not None:
                run.first_audio_ms.append(event["first_audio_ms"])

        session = LiveSession(services, receive)
        holder["s"] = session
        config = json.loads(json.dumps(SESSION))
        config["localive"] = {"metrics": True}
        if self.brain:
            config["delegation"]["responses"]["model"] = self.brain
        await session.start(config)
        return session

    @staticmethod
    async def idle(session: LiveSession, seconds: float = 60) -> None:
        """Until the reply is written and fully played."""
        await asyncio.sleep(0.3)
        end = time.monotonic() + seconds
        while time.monotonic() < end:
            if not session._turn_open and not session.speaking:
                return
            await asyncio.sleep(0.05)

    @staticmethod
    async def speaking(session: LiveSession, sentences: int = 1, seconds: float = 40) -> None:
        end = time.monotonic() + seconds
        while time.monotonic() < end:
            if session.output.busy and len([s for s in session._sentences.values()
                                            if s.done]) >= sentences:  # fmt: skip
                return
            await asyncio.sleep(0.05)


# ------------------------------------------------------------------ checks
EMOJI = re.compile("[\U0001f300-\U0001faff☀-➿]")
ENGLISH = {"the", "and", "was", "she", "he", "his", "her", "with", "that", "once", "upon",
           "time", "there", "cat", "who", "in", "a", "of", "to"}
FRENCH = {"le", "la", "les", "et", "était", "une", "un", "qui", "dans", "il", "elle", "de"}


def words(text: str) -> list[str]:
    return re.findall(r"[a-zàâçéèêëîïôûùüÿœ']+", text.lower())


def spoken(run: Run) -> str:
    return " ".join(run.said)


def clean_speech(run: Run) -> bool:
    text = spoken(run)
    return not (EMOJI.search(text) or re.search(r"[*#`|]|^\s*[-•]\s", text, re.M))


def no_announcement(text: str) -> bool:
    return not re.search(r"\bje (vais|m'apprête à) (te |vous )?(raconter|dire|faire|donner)",
                         text.lower())


def tool_names(run: Run) -> list[str]:
    return [name for name, _ in run.tools]


# --------------------------------------------------------------- scenarios
async def simple(h: Harness, run: Run, question: str) -> LiveSession:
    s = await h.session(run)
    await s.on_user_text(question)
    await h.idle(s)
    return s


async def heure(h, run):
    s = await simple(h, run, "Quelle heure est-il ?")
    run.checks["appelle clock__read"] = "clock__read" in tool_names(run)
    run.checks["pas de carte en doublon"] = "ui__show_luna_card" not in tool_names(run)
    run.checks["dit l'heure"] = bool(re.search(r"14|quatorze", spoken(run)))
    run.checks["court"] = len(run.said) <= 2
    await s.close("bench")


async def meteo(h, run):
    s = await simple(h, run, "Quel temps fera-t-il demain ?")
    run.checks["appelle weather__read"] = "weather__read" in tool_names(run)
    run.checks["dit la prévision"] = bool(re.search(r"15|quinze|soleil", spoken(run).lower()))
    await s.close("bench")


async def culture(h, run):
    s = await simple(h, run, "Quelle est la capitale de l'Australie ?")
    run.checks["répond Canberra"] = "canberra" in spoken(run).lower()
    run.checks["pas d'outil de module"] = not {"clock__read", "weather__read",
                                                "transit__read"} & set(tool_names(run))
    run.checks["court"] = len(run.said) <= 2
    await s.close("bench")


async def calcul(h, run):
    s = await simple(h, run, "Combien font 37 fois 12 ?")
    run.checks["répond 444"] = bool(re.search(r"444|quatre cent quarante-quatre",
                                              spoken(run).lower()))
    run.checks["pas d'outil de module"] = not {"clock__read", "weather__read",
                                                "transit__read"} & set(tool_names(run))
    await s.close("bench")


async def histoire_suite(h, run):
    s = await simple(h, run, "Raconte-moi une histoire très courte sur un dragon.")
    first = len(run.said)
    tools_before = len(run.tools)
    await s.on_user_text("Tu peux continuer l'histoire ?")
    await h.idle(s)
    suite = " ".join(run.said[first:])
    run.checks["raconte une histoire"] = "dragon" in " ".join(run.said[:first]).lower()
    run.checks["continue sans outil"] = len(run.tools) == tools_before
    run.checks["la suite existe"] = len(suite) > 80
    run.checks["sans annonce"] = no_announcement(suite)
    await s.close("bench")


async def correction_anglais(h, run):
    s = await h.session(run)
    await s.on_user_text("Raconte-moi une histoire de 150 mots sur un chat.")
    await h.speaking(s, 2)
    mark = len(run.said)
    await s.on_user_text("Tu peux la raconter en anglais plutôt ?")
    await h.idle(s)
    after = " ".join(run.said[mark + 1:])  # the sentence being said ends in French
    w = words(after)
    english = sum(x in ENGLISH for x in w) / max(1, len(w))
    run.checks["décision correction"] = any(d.startswith("ADD") for d in run.decisions)
    run.checks["refait en anglais"] = english > 0.15 and len(after) > 150
    run.checks["sans annonce"] = no_announcement(after) and not re.search(
        r"(i will|i'll) (tell|now)", after.lower())
    await s.close("bench")


async def ajout_apres(h, run):
    s = await h.session(run)
    await s.on_user_text("Donne-moi trois idées de recettes avec des courgettes, en détaillant.")
    await h.speaking(s, 1)
    await s.on_user_text("Et une idée de dessert aussi.")
    await h.idle(s, 90)
    text = spoken(run).lower()
    run.checks["pas coupé net"] = run.interrupted == 0
    run.checks["répond au dessert"] = bool(re.search(r"dessert|gâteau|tarte|crème|mousse|sucr",
                                                     text))
    run.checks["courgettes dites"] = "courgette" in text
    await s.close("bench")


